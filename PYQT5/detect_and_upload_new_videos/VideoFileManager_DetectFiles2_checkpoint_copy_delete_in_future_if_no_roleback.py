from functools import wraps

class FunctionUseCounter:
    def __init__(self):
        self.counts = {}

    def track(self, func):
        """Decorator method to attach to functions."""
        self.counts[func.__name__] = 0

        @wraps(func)
        def wrapper(*args, **kwargs):
            self.counts[func.__name__] += 1
            return func(*args, **kwargs)

        return wrapper

    def get_most_used(self):
        """Returns the dictionary sorted from most called to least called."""
        return dict(sorted(self.counts.items(), key=lambda item: item[1], reverse=True))

    def reset(self):
        """Resets all function counts back to 0."""
        for name in self.counts:
            self.counts[name] = 0


